import { inMirrorFamily } from "../../lib/mirror.js";

/**
 * ── #253 — self-mirror 대조는 **러너의 몫**이다(설계 2026-09-30 §8.3 S3, DECISIONS 1.4.35) ───────────
 *
 * 러너의 mirrorStep(`factory/lib/mirror.js`)은 빌더 핸드오프 **뒤에** 설치본 `.factory/**`·`.claude/hooks/*.sh`를
 * `factory/**`에서 다시 만든다. 그러니 `factory/**`를 고친 빌더 세션 안에서 `self-mirror.test.js`의 네 가족 대조는
 * 언제나 RED이고, 빌더가 그 RED를 자기 결함으로 읽어 미러를 직접 재생성·커밋하면 오버레이 가드가 런을 blocked으로
 * 세운다(#233). 이 모듈은 그 판단 하나만 한다.
 *
 * 빌더 세션의 판정은 `FACTORY_STAGE === "implement"` **하나뿐**이다 — `stageClaudeEnv`(run-stage.js)가 `claude -p`
 * 세션에만 심는 값이다. 이슈 초안의 대체 판정(`FACTORY_RUNNER_ID` + `.factory/out/context.json`)은 쓰지 않는다:
 * 러너 자신의 게이트 프로세스(mirrorStep 직후의 unit 게이트)가 정확히 그 모양이고, 그 자리가 이 바이트 대조가
 * 반드시 물어야 하는 곳이다. `transition.js`의 `isAgentSession`도 재사용하지 않는다 — 그것은 운영자 세션
 * (`CLAUDE_PROJECT_DIR`)까지 포함해 바이트 대조를 사람 앞에서도 꺼 버린다.
 *
 * 이 파일은 `factory/test/helpers/`에 있다(미러되는 엔진 `factory/lib`가 아니다) — 테스트만의 개념이 설치본에 실리지 않게.
 * env는 언제나 인자로 받는다: 이 판단을 고정하는 테스트 자신이 빌더 세션 안에서 돌기 때문이다.
 */
export const BUILDER_SESSION_NOTE = "self-mirror: skipped inside a builder session — the runner regenerates .factory/** after the handoff (mirrorStep)";

/** 빌더 세션(implement 스테이지의 `claude -p`)인가. review·merge·러너·CI·사람 세션은 전부 false. */
export const isBuilderSession = (env = {}) => env?.FACTORY_STAGE === "implement";

/**
 * 드리프트한 경로 목록(`bad`)에 대한 판정.
 *  - 드리프트 없음 → `{ ok: true }` (진짜 비교로 통과한 것에 노트를 붙이지 않는다).
 *  - 빌더 세션이고 드리프트가 전부 mirrorStep의 가족(`inMirrorFamily`) → `{ ok: true, note }`, 노트를 한 번 출력한다.
 *  - 빌더 세션인데 가족 밖 경로가 드리프트(예: `.claude/commands/factory-*.md` — mirrorStep이 만들지 않는다) → RED.
 *    그 메시지는 재생성·커밋을 시키지 않는다(#233의 빌더가 따른 지시가 바로 그것이었다).
 *  - 그 밖의 모든 세션 → 오늘과 같은 RED(`<paths> — <hint>`).
 * @returns {{ok:boolean, note?:string, message?:string}}
 */
export function selfMirrorVerdict({ bad, env = {}, hint }) {
  if (!bad.length) return { ok: true };
  if (!isBuilderSession(env)) return { ok: false, message: `${bad.join(", ")} — ${hint}` };
  const outside = bad.filter((dest) => !inMirrorFamily(dest));
  if (outside.length) {
    return {
      ok: false,
      message: `${outside.join(", ")} — not regenerated by the runner's mirrorStep; inside a builder session do not write it yourself, the path is owned by the runner or the operator`,
    };
  }
  console.log(BUILDER_SESSION_NOTE);
  return { ok: true, note: BUILDER_SESSION_NOTE };
}
